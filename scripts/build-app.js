const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const modules = [
  '00-core.js',
  '01-shared-views.js',
  '02-bookings-documents.js',
  '03-fleet-customers-forms.js',
  '04-supabase-data-and-auth.js',
  '05-navigation-and-quotes.js',
  '06-customer-finance-document-views.js',
  '07-payments-and-notifications.js',
  '08-settings-and-document-output.js',
  '09-table-sorting-and-pagination.js',
  '10-payment-management.js',
  '10a-quote-workflows.js',
  '11-startup.js',
];
const source = modules.map((name) => fs.readFileSync(path.join(root, 'src', 'app', name), 'utf8').trim()).join('\n\n');
const output = ['(()=>{', '// Generated by scripts/build-app.js from src/app/*.js. Edit those files instead.', source, '})();', ''].join('\n');
fs.writeFileSync(path.join(root, 'app.js'), output, 'utf8');
console.log(`Built app.js from ${modules.length} source modules.`);
